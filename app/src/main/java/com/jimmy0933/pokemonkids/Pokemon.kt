/** Every round has 8 Pokemon (16 cards, 4x4 grid). The first 100 rounds
 * cover the whole Dex 1-800 in order (100 rounds x 8 = 800); rounds 101-120
 * are review rounds that replay Dex 1-160 in order, so the kid meets the
 * early Pokemon again. 120 rounds in total. */
const val ROUND_SIZE = 8

/** Review rounds replay Dex 1-160 in order: 20 rounds of 8. */
const val REVIEW_ROUND_COUNT = 20

/** Pokemon per round: 8 for every round (see above). */
fun roundSize(roundIndex: Int): Int = ROUND_SIZE

/** The rounds: the 800 Pokemon in groups of 8, in Dex order, followed by
 * 20 review rounds replaying Dex 1-160 in order. */
fun rounds(): List<List<Pokemon>> =
    ALL_POKEMON.chunked(ROUND_SIZE) +
        ALL_POKEMON.take(REVIEW_ROUND_COUNT * ROUND_SIZE).chunked(ROUND_SIZE)

val TOTAL_ROUNDS: Int get() = rounds().size

/** The cards for a round: each Pokemon twice, shuffled. Pure function, unit-tested. */
fun roundCards(roundIndex: Int, seed: Long = 0L): List<Pokemon> {
    val round = rounds()[roundIndex]
    val cards = round + round
    return if (seed == 0L) cards.shuffled() else cards.shuffled(kotlin.random.Random(seed))
}

/** True when every Pokemon in the round has been matched. */
fun isRoundComplete(matchedIds: Set<Int>, roundIndex: Int): Boolean =
    rounds()[roundIndex].all { it.id in matchedIds }

/** The seven Pokedex regions, by Dex number. */
enum class Region(val label: String, val range: IntRange) {
    KANTO("關都", 1..151),
    JOHTO("城都", 152..251),
    HOENN("豐緣", 252..386),
    SINNOH("神奧", 387..493),
    UNOVA("合眾", 494..649),
    KALOS("卡洛斯", 650..721),
    ALOLA("阿羅拉", 722..800),
}

fun regionOf(pokemon: Pokemon): Region =
    Region.entries.first { pokemon.id in it.range }

fun regionPokemon(region: Region): List<Pokemon> =
    ALL_POKEMON.filter { it.id in region.range }

/** The whole evolution family this Pokemon belongs to (all Pokemon connected
 * through evolvesFrom/evolvesTo), sorted by Dex number. Pure function,
 * unit-tested. Branched families (e.g. Eevee) come back as one flat list. */
fun Pokemon.evolutionFamily(): List<Pokemon> {
    val byId = ALL_POKEMON.associateBy { it.id }
    val seen = mutableSetOf<Int>()
    val queue = ArrayDeque<Int>()
    queue.add(id)
    while (queue.isNotEmpty()) {
        val current = queue.removeFirst()
        if (!seen.add(current)) continue
        val pokemon = byId[current] ?: continue
        pokemon.evolvesFrom?.let { queue.add(it) }
        pokemon.evolvesTo.forEach { queue.add(it) }
    }
    return seen.mapNotNull { byId[it] }.sortedBy { it.id }
}

/** One quiz question: the answer and its picture options (answer included). */
data class QuizQuestion(val answer: Pokemon, val options: List<Pokemon>)

const val QUIZ_QUESTION_COUNT = 40
const val LISTEN_OPTION_COUNT = 4
const val SILHOUETTE_OPTION_COUNT = 3

/** Build [count] quiz questions from [pool]. Answers prefer Pokemon the kid
 * has not collected yet, so playing fills the Pokedex; options always include
 * the answer and are unique. Pure function, unit-tested. */
fun makeQuizQuestions(
    pool: List<Pokemon>,
    collectedIds: Set<Int>,
    count: Int,
    optionCount: Int,
    seed: Long,
): List<QuizQuestion> {
    val random = kotlin.random.Random(seed)
    val uncollected = pool.filter { it.id !in collectedIds }.shuffled(random)
    val collected = pool.filter { it.id in collectedIds }.shuffled(random)
    val answers = (uncollected + collected).take(count)
    return answers.map { answer ->
        val others = pool.filter { it.id != answer.id }
            .shuffled(random).take(optionCount - 1)
        QuizQuestion(answer, (others + answer).shuffled(random))
    }
}
